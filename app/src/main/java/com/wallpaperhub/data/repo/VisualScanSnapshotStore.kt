package com.wallpaperhub.data.repo

import android.content.Context
import android.net.Uri
import com.wallpaperhub.analysis.DuplicateKind
import com.wallpaperhub.analysis.VisualDuplicateScanner
import com.wallpaperhub.data.db.CURRENT_MEDIA_ANALYSIS_VERSION
import com.wallpaperhub.data.db.MediaAnalysisEntity
import com.wallpaperhub.data.db.WallpaperEntity
import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import java.security.MessageDigest

/**
 * Persistent result cache for the expensive visual-similarity pass.
 *
 * The media_analysis table owns per-item fingerprints. This file stores only the derived grouping
 * result so reopening the app or installing a newer debug APK does not make the user repeat a
 * 20-minute gallery scan.
 *
 * Snapshot identity is intentionally tied to the VISUAL fingerprint schema, not to the broader
 * media-analysis/quality schema. Quality scoring may move from V1 -> V2 -> V3 without changing the
 * dHash sequence used for visual grouping; such a quality-only migration must not invalidate an
 * already completed visual scan.
 */
class VisualScanSnapshotStore(context: Context) {
    private val appContext = context.applicationContext
    private val file = File(appContext.filesDir, FILE_NAME)

    data class Snapshot(
        val librarySignature: String,
        val groups: List<VisualDuplicateScanner.Group>,
        val scannedCount: Int,
        val failedCount: Int,
        val savedAt: Long,
    )

    fun load(): Snapshot? = runCatching {
        if (!file.isFile || file.length() <= 0L) return@runCatching null
        val root = JSONObject(file.readText())
        if (root.optInt("version", -1) != SNAPSHOT_VERSION) return@runCatching null
        val groupsJson = root.optJSONArray("groups") ?: JSONArray()
        val groups = ArrayList<VisualDuplicateScanner.Group>(groupsJson.length())
        for (index in 0 until groupsJson.length()) {
            val item = groupsJson.getJSONObject(index)
            val idsJson = item.optJSONArray("wallpaperIds") ?: JSONArray()
            val ids = ArrayList<String>(idsJson.length())
            for (idIndex in 0 until idsJson.length()) ids += idsJson.getString(idIndex)
            val kind = runCatching { DuplicateKind.valueOf(item.getString("kind")) }.getOrNull() ?: continue
            groups += VisualDuplicateScanner.Group(
                fingerprint = item.getString("fingerprint"),
                kind = kind,
                wallpaperIds = ids,
                similarity = item.optDouble("similarity", 0.0),
                totalBytes = item.optLong("totalBytes", 0L),
            )
        }
        Snapshot(
            librarySignature = root.getString("librarySignature"),
            groups = groups,
            scannedCount = root.optInt("scannedCount", 0),
            failedCount = root.optInt("failedCount", 0),
            savedAt = root.optLong("savedAt", 0L),
        )
    }.getOrNull()

    fun save(
        librarySignature: String,
        groups: List<VisualDuplicateScanner.Group>,
        scannedCount: Int,
        failedCount: Int,
    ) {
        runCatching {
            val groupsJson = JSONArray()
            groups.forEach { group ->
                val ids = JSONArray()
                group.wallpaperIds.forEach(ids::put)
                groupsJson.put(
                    JSONObject()
                        .put("fingerprint", group.fingerprint)
                        .put("kind", group.kind.name)
                        .put("wallpaperIds", ids)
                        .put("similarity", group.similarity)
                        .put("totalBytes", group.totalBytes)
                )
            }
            val root = JSONObject()
                .put("version", SNAPSHOT_VERSION)
                .put("librarySignature", librarySignature)
                .put("scannedCount", scannedCount)
                .put("failedCount", failedCount)
                .put("savedAt", System.currentTimeMillis())
                .put("groups", groupsJson)
            file.parentFile?.mkdirs()
            val temp = File(file.parentFile, "${file.name}.tmp")
            temp.writeText(root.toString())
            if (!temp.renameTo(file)) {
                file.writeText(root.toString())
                temp.delete()
            }
        }
    }

    /**
     * Stable visual identity. UI/session state and quality-analysis versions intentionally do not
     * invalidate similarity work.
     *
     * Existing installs may already hold a snapshot generated by the older signature formula that
     * included MediaAnalysisEntity.analysisVersion. Before switching to the stable visual formula,
     * accept any legacy V1..current signature that exactly matches the current cached visual hashes.
     * This makes the V1 -> Quality V2 migration one-time compatible instead of forcing 7k+ media to
     * present another full "Scanning 0/N" pass.
     */
    fun librarySignature(
        wallpapers: List<WallpaperEntity>,
        analysisRows: List<MediaAnalysisEntity>,
    ): String {
        val analysisById = analysisRows.associateBy { it.wallpaperId }
        val stable = stableVisualSignature(wallpapers, analysisById)
        val persisted = load()?.librarySignature ?: return stable

        if (persisted == stable) return stable

        for (version in 1..CURRENT_MEDIA_ANALYSIS_VERSION.coerceAtLeast(1)) {
            val legacy = legacySignature(wallpapers, analysisById, version)
            if (persisted == legacy) return persisted
        }

        return stable
    }

    private fun stableVisualSignature(
        wallpapers: List<WallpaperEntity>,
        analysisById: Map<String, MediaAnalysisEntity>,
    ): String {
        val digest = MessageDigest.getInstance("SHA-256")
        update(digest, "visual-fingerprint-v$VISUAL_FINGERPRINT_VERSION")
        wallpapers.sortedBy { it.id }.forEach { wallpaper ->
            val row = analysisById[wallpaper.id]
            val uri = Uri.parse(wallpaper.uri)
            update(digest, wallpaper.id)
            update(digest, wallpaper.uri)
            update(digest, wallpaper.type.name)
            update(digest, currentSize(uri).toString())
            update(digest, currentLastModified(uri).toString())
            update(digest, row?.sourceSizeBytes?.toString() ?: "missing")
            update(digest, row?.visualHashSequence ?: "missing")
        }
        return finish(digest)
    }

    /** Reproduces the pre-fix signature so already-saved V1/V2 snapshots remain usable. */
    private fun legacySignature(
        wallpapers: List<WallpaperEntity>,
        analysisById: Map<String, MediaAnalysisEntity>,
        analysisVersion: Int,
    ): String {
        val digest = MessageDigest.getInstance("SHA-256")
        wallpapers.sortedBy { it.id }.forEach { wallpaper ->
            val row = analysisById[wallpaper.id]
            val uri = Uri.parse(wallpaper.uri)
            val legacyRowRevision = if (analysisVersion == 1 && uri.scheme != "file") {
                // V1 stored 0 for content:// last-modified.
                0L
            } else {
                row?.sourceLastModified
            }
            update(digest, wallpaper.id)
            update(digest, wallpaper.uri)
            update(digest, wallpaper.type.name)
            update(digest, currentSize(uri).toString())
            update(digest, currentLastModified(uri).toString())
            update(digest, if (row == null) "missing" else analysisVersion.toString())
            update(digest, row?.status ?: "missing")
            update(digest, row?.sourceSizeBytes?.toString() ?: "missing")
            update(digest, legacyRowRevision?.toString() ?: "missing")
            update(digest, row?.visualHashSequence ?: "missing")
        }
        return finish(digest)
    }

    private fun currentSize(uri: Uri): Long {
        if (uri.scheme == "file") return uri.path?.let(::File)?.takeIf(File::isFile)?.length() ?: -1L
        return runCatching { appContext.contentResolver.openAssetFileDescriptor(uri, "r")?.use { it.length } }
            .getOrNull()?.takeIf { it >= 0L } ?: -1L
    }

    private fun currentLastModified(uri: Uri): Long {
        if (uri.scheme == "file") return uri.path?.let(::File)?.takeIf(File::exists)?.lastModified() ?: 0L
        return 0L
    }

    private fun finish(digest: MessageDigest): String = digest.digest().joinToString("") { byte ->
        (byte.toInt() and 0xff).toString(16).padStart(2, '0')
    }

    private fun update(digest: MessageDigest, value: String) {
        digest.update(value.toByteArray(Charsets.UTF_8))
        digest.update(0.toByte())
    }

    private companion object {
        const val SNAPSHOT_VERSION = 1
        const val VISUAL_FINGERPRINT_VERSION = 1
        const val FILE_NAME = "visual_similarity_snapshot_v1.json"
    }
}
